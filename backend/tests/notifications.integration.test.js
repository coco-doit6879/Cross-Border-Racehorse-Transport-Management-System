const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const mongoose = require('mongoose');
const express = require('express');
const jwt = require('jsonwebtoken');
const User = require('../src/models/User');
const Order = require('../src/models/Order');
const Route = require('../src/models/TransportRoute');
const Notice = require('../src/models/Notification');
const service = require('../src/services/notifications');

test('persistent inbox: role delivery, deduplication, private rooms, pagination and read ownership', { timeout: 30000 }, async t => {
  const dbName = `cbrt_notifications_test_${randomUUID().replaceAll('-', '')}`;
  await mongoose.connect('mongodb://127.0.0.1:27017', { dbName, serverSelectionTimeoutMS: 5000 });
  t.after(async () => { service.setIO(null); assert.equal(mongoose.connection.name, dbName); assert.match(dbName, /^cbrt_notifications_test_[a-f0-9]{32}$/); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  await Promise.all([Notice.init(), User.init(), Order.init(), Route.init()]);
  const makeUser = async (name, role) => User.create({ username: name, email: `${name}@test.local`, fullName: name, password: 'testing123', phone: '0900000000', role });
  const customer = await makeUser('customer', 'CUSTOMER'), other = await makeUser('other', 'CUSTOMER');
  const specialist = await makeUser('specialist', 'TRANSPORT_SPECIALIST'), manager = await makeUser('manager', 'LOGISTICS_MANAGER');
  const fleet = await makeUser('fleet', 'FLEET_COORDINATOR'), driver = await makeUser('driver', 'DRIVER');
  const inactive = await makeUser('inactive', 'TRANSPORT_SPECIALIST'); inactive.isActive = false; await inactive.save();
  const orderId = new mongoose.Types.ObjectId(), routeId = new mongoose.Types.ObjectId();
  // Minimal fixtures bypass unrelated order validation; all data remains in this run's isolated database.
  await Order.collection.insertOne({ _id: orderId, customerId: customer._id, bookingCode: 'TR-NOTICE-TEST' });
  await Route.collection.insertOne({ _id: routeId, orderId, driverId: driver._id });
  const emitted = []; service.setIO({ to(room) { return { emit(event) { emitted.push({ room, event }); } }; } });
  await service.orderEvent('DOC_REQUESTED', orderId, 'doc-1', { category: 'HORSE', reason: 'Bổ sung giấy tiêm phòng' });
  await service.orderEvent('DOC_REQUESTED', orderId, 'doc-1', { category: 'HORSE' });
  assert.equal(await Notice.countDocuments(), 1, 'same event is not duplicated');
  const item = await Notice.findOne();
  assert.equal(String(item.recipientId), String(customer._id));
  assert.equal(item.webPath, `/orders/${orderId}?tab=documents`);
  assert.equal(emitted[0].room, `user_${customer._id}`);
  assert.equal(emitted.length, 1);
  await service.orderEvent('DOC_SUBMITTED', orderId, 'submission-1');
  assert.equal(await Notice.countDocuments({ recipientId: specialist._id }), 1);
  assert.equal(await Notice.countDocuments({ recipientId: inactive._id }), 0);
  await service.orderEvent('DEPARTURE_READY', orderId, 'ready-1');
  const driverItem = await Notice.findOne({ recipientId: driver._id });
  assert.equal(driverItem.mobilePath, `/trips/${routeId}`);
  await service.orderEvent('PLAN_CONFIRMED', orderId, 'plan-1');
  assert.equal((await Notice.findOne({ recipientId: manager._id })).webPath, `/manager/approvals?orderId=${orderId}`);
  await service.orderEvent('SOS', orderId, 'incident-1', { reason: 'Khẩn cấp' });
  assert.equal(await Notice.countDocuments({ urgent: true }), 2, 'SOS goes only to management and dispatch');
  assert.equal((await Notice.findOne({ urgent: true, recipientId: fleet._id })).webPath, '/incidents/sos');
  await service.acknowledgeSOS('incident-1');
  assert.equal(await Notice.countDocuments({ urgent: true }), 0, 'handled SOS no longer raises urgent popups');
  assert.equal(await Notice.countDocuments({ eventKey: 'SOS:incident-1' }), 2, 'SOS history remains available');
  const horse = { _id: new mongoose.Types.ObjectId(), ownerId: customer._id, name: 'Test horse', microchipId: 'TEST-CHIP', __v: 1 };
  await service.horseEvent(horse);
  assert.ok(await Notice.exists({ recipientId: specialist._id, eventKey: `HORSE:${horse._id}:1:PENDING_REVIEW` }));
  await service.horseEvent({ ...horse, reviewNotes: 'Cần bổ sung ảnh giấy tiêm phòng' }, 'REJECTED');
  const healthNotice = await Notice.findOne({ recipientId: customer._id, eventKey: `HORSE:${horse._id}:1:REJECTED` });
  assert.equal(healthNotice.webPath, `/horses/${horse._id}`);
  assert.equal(healthNotice.message, 'Cần bổ sung ảnh giấy tiêm phòng');
  const app = express(); app.use(express.json()); app.use('/notifications', require('../src/routes/notificationRoutes'));
  app.use((err, req, res, next) => res.status(500).json({ message: err.message }));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const send = async (path, user, method = 'GET', body) => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/notifications${path}`, { method, headers: { 'Content-Type': 'application/json', ...(user ? { Authorization: `Bearer ${jwt.sign({ id: String(user._id) }, process.env.JWT_SECRET || 'cbrt_super_secret_jwt_key_2026')}` } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, body: await response.json() };
  };
  assert.equal((await send('', null)).status, 401);
  assert.equal((await send('', other)).body.data.length, 0);
  assert.equal((await send(`/${item._id}/read`, other, 'PATCH')).status, 404);
  assert.equal((await send(`/${item._id}/read`, customer, 'PATCH')).status, 200);
  assert.ok((await Notice.findById(item._id)).readAt);
  await service.deliver([customer], 'after-cutoff', () => ({ title: 'New', message: 'New', webPath: '/orders' }));
  await send('/read-all', customer, 'PATCH', { through: String(item._id) });
  assert.equal((await Notice.findOne({ eventKey: 'after-cutoff' })).readAt, null, 'read-all preserves later arrivals');
  for (let i = 0; i < 35; i++) await service.deliver([customer], `page-${i}`, () => ({ title: 'Test', message: 'Test', webPath: '/orders' }));
  const page = (await send('', customer)).body;
  assert.equal(page.data.length, 30); assert.equal(page.hasMore, true);
  const nextPage = (await send(`?before=${page.data[29]._id}`, customer)).body;
  assert.ok(nextPage.data.length > 0); assert.ok(nextPage.data.every(n => !page.data.some(x => x._id === n._id)));
  assert.equal((await send('?before=invalid', customer)).status, 400);
});
